    private void simpanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanButtonActionPerformed
                                              
    // Mengambil data dari form
    String nama = namaField.getText();
    String npm = npmField.getText();
    String prodi = (String) prodiComboBox.getSelectedItem();
    int semester = (Integer) semesterSpiner.getValue();
    String email = emailField.getText();
    String hp = hpField.getText();
    String alamat = alamatTextArea.getText();
    
    // Menampilkan data sebagai bukti bahwa tombol berfungsi
    javax.swing.JOptionPane.showMessageDialog(this, 
        "Data Berhasil Disimpan!\n\n" +
        "Nama: " + nama + "\n" +
        "NPM: " + npm + "\n" +
        "Program Studi: " + prodi + "\n" +
        "Semester: " + semester + "\n" +
        "Email: " + email + "\n" +
        "No HP: " + hp + "\n" +
        "Alamat: " + alamat
    );
        // TODO add your handling code here:
    }//GEN-LAST:event_simpanButtonActionPerformed

