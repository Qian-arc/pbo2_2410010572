    // --- Logika Validasi dan Penyimpanan ---
    private void simpan() {
        String judul = judulField.getText().trim();
        String penulis = penulisField.getText().trim();
        String penerbit = penerbitField.getText().trim();
        String tahunStr = tahunField.getText().trim();

        // Validasi: Judul wajib diisi
        if (judul.isEmpty()) {
            pesanLabel.setText("Judul buku wajib diisi");
            judulField.requestFocusInWindow();
            return;
        }
        
        // Validasi: Penulis wajib diisi
        if (penulis.isEmpty()) {
            pesanLabel.setText("Penulis wajib diisi");
            penulisField.requestFocusInWindow();
            return;
        }

        // Validasi: Tahun harus berupa angka valid
        int tahun;
        try {
            tahun = Integer.parseInt(tahunStr);
        } catch (NumberFormatException e) {
            pesanLabel.setText("Tahun terbit harus berupa angka valid");
            tahunField.requestFocusInWindow();
            return;
        }

        KategoriBuku kategori = (KategoriBuku) kategoriCombo.getSelectedItem();
        hasil = new Buku(judul, penulis, penerbit, tahun, kategori);
        dispose(); // Tutup dialog jika data sudah valid
    }
    
    /** Menampilkan dialog dan mengembalikan objek Buku atau null jika dibatalkan */
    public Buku tampilkan() {
        setVisible(true);
        return hasil;
    }

